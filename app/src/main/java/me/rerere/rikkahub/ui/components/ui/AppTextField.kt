val AppTextFieldShape: Shape = RoundedCornerShape(14.dp)

@Composable
fun appOutlinedTextFieldColors(
    colors: TextFieldColors? = null,
): TextFieldColors {
    if (colors != null) return colors
    val scheme = MaterialTheme.colorScheme
    val containerColor = scheme.surfaceContainerLow.copy(alpha = 0.35f)
    val disabledContainer = scheme.surfaceContainerLow.copy(alpha = 0.18f)
    return OutlinedTextFieldDefaults.colors(
        focusedContainerColor = containerColor,
        unfocusedContainerColor = containerColor,
        disabledContainerColor = disabledContainer,
        focusedBorderColor = scheme.primary.copy(alpha = 0.85f),
        unfocusedBorderColor = scheme.outlineVariant.copy(alpha = 0.72f),
        disabledBorderColor = scheme.outlineVariant.copy(alpha = 0.35f),
    )
}

/**
 * 统一风格的轻量圆角输入框：14.dp 圆角、柔和边框与微弱底色，替代生硬的默认 M3 方框。
